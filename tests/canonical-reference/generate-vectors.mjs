// Writes packages/core/test/canonical/vectors.json.
// Expected canonical texts are typed by hand below (from RFC 8785 and from the ECMAScript number
// rules). Hashes are SHA-256 of those literal texts, computed with node:crypto, so the file does
// not depend on any canonicalizer. Run: node tests/canonical-reference/generate-vectors.mjs
import { createHash } from 'node:crypto';
import fs from 'node:fs';

const sha = (text) => createHash('sha256').update(text, 'utf8').digest('hex');
const U = (...codes) => String.fromCharCode(...codes);

const vectors = [
  {
    name: 'rfc8785-sample',
    note: 'Official RFC 8785 example. Contains 1e30, so it is encode-only: WEAVE refuses it as a value.',
    inputJson:
      '{"numbers":[333333333.33333329,1E30,4.50,2e-3,0.000000000000000000000000001],"string":"\\u20ac$\\u000F\\u000aA\'\\u0042\\u0022\\u005c\\\\\\"/","literals":[null,true,false]}',
    canonical:
      '{"literals":[null,true,false],"numbers":[333333333.3333333,1e+30,4.5,0.002,1e-27],"string":"' +
      U(0x20ac) +
      '$\\u000f\\nA\'B\\"\\\\\\\\\\"/"}',
    supported: false,
  },
  {
    name: 'rfc8785-key-order',
    note: 'RFC 8785 section 3.2.3 sorting example (UTF-16 code unit order).',
    inputJson:
      '{"\\u20ac":"Euro Sign","\\r":"Carriage Return","\\ufb33":"Hebrew Letter Dalet With Dagesh","1":"One","\\ud83d\\ude00":"Emoji: Grinning Face","\\u0080":"Control","\\u00f6":"Latin Small Letter O With Diaeresis"}',
    canonical:
      '{"\\r":"Carriage Return","1":"One","' +
      U(0x80) +
      '":"Control","' +
      U(0xf6) +
      '":"Latin Small Letter O With Diaeresis","' +
      U(0x20ac) +
      '":"Euro Sign","' +
      U(0xd83d, 0xde00) +
      '":"Emoji: Grinning Face","' +
      U(0xfb33) +
      '":"Hebrew Letter Dalet With Dagesh"}',
    supported: true,
  },
  {
    name: 'utf16-vs-utf8-property-order',
    note: 'U+10000 sorts BEFORE U+E000 in UTF-16 (D800 < E000) but AFTER it in UTF-8 (F0 > EE). Canonical JSON uses UTF-16.',
    inputJson: '{"\\ue000":1,"\\ud800\\udc00":2}',
    canonical: '{"' + U(0xd800, 0xdc00) + '":2,"' + U(0xe000) + '":1}',
    supported: true,
  },
  {
    name: 'negative-zero',
    inputJson: '-0',
    canonical: '0',
    supported: true,
  },
  {
    name: 'numbers',
    inputJson: '[0.1,100,4.5,1.5e-7,1e-7,9007199254740991,-9007199254740991,0.30000000000000004,0]',
    canonical: '[0.1,100,4.5,1.5e-7,1e-7,9007199254740991,-9007199254740991,0.30000000000000004,0]',
    supported: true,
  },
  {
    name: 'big-number-forms',
    note: 'Valid RFC 8785 output, but integers beyond the safe range are refused as values (D7).',
    inputJson: '[1e21,123456789012345680000]',
    canonical: '[1e+21,123456789012345680000]',
    supported: false,
  },
  {
    name: 'nested-and-empty',
    inputJson: '{"b":{},"a":[],"c":[{"z":1,"y":[]}]}',
    canonical: '{"a":[],"b":{},"c":[{"y":[],"z":1}]}',
    supported: true,
  },
  {
    name: 'string-escapes',
    inputJson: '"\\u0000\\u001f\\u007f\\"\\\\/\\b\\f\\n\\r\\t"',
    canonical: '"\\u0000\\u001f' + U(0x7f) + '\\"\\\\/\\b\\f\\n\\r\\t"',
    supported: true,
  },
  {
    name: 'non-ascii-strings-not-normalized',
    note: 'Strings are not Unicode-normalized: precomposed and decomposed forms stay different.',
    inputJson: '["\\u00e9","e\\u0301"]',
    canonical: '["' + U(0xe9) + '","e' + U(0x301) + '"]',
    supported: true,
  },
  {
    name: 'op-payload',
    note: 'A complete D2 payload. The op hash is the sha256 of this canonical text (no hash, no wallTime).',
    inputJson:
      '{"replicaId":"aaaaaaaaaaaaaaaaaaaaaaaaaa","seq":1,"lamport":1,"context":{},"collection":"notes","recordId":"r1","kind":"set","schemaVersion":1,"fields":{"title":"Hello"}}',
    canonical:
      '{"collection":"notes","context":{},"fields":{"title":"Hello"},"kind":"set","lamport":1,"recordId":"r1","replicaId":"aaaaaaaaaaaaaaaaaaaaaaaaaa","schemaVersion":1,"seq":1}',
    supported: true,
  },
];
for (const v of vectors) v.sha256 = sha(v.canonical);

const out = {
  description:
    'Canonical encoding test vectors (D7, R15.10). Loaded by Node tests and by the Chromium test (T2.8). Generated by tests/canonical-reference/generate-vectors.mjs.',
  vectors,
  setUnion: [
    {
      name: 'strings-utf8-order',
      note: 'Set-union output is sorted by the UTF-8 bytes of each element canonical encoding: U+E000 (EE 80 80) before U+10000 (F0 90 80 80).',
      inputJson: JSON.stringify(['b', 'a', 'a', U(0xe9), U(0xd800, 0xdc00), U(0xe000), 'z']),
      expectedJson: JSON.stringify(['a', 'b', 'z', U(0xe9), U(0xe000), U(0xd800, 0xdc00)]),
    },
    {
      name: 'mixed-types',
      note: 'Equality is by canonical encoding, so 3 and "3" are different; order is by encoding bytes.',
      inputJson: '[3,"3",3,{"a":1},{"a":1},[1],true,null,"3"]',
      expectedJson: '["3",3,[1],null,true,{"a":1}]',
    },
  ],
  rejectedJson: [
    { name: 'unsafe-integer', inputJson: '9007199254740993' },
    { name: 'large-integer-valued-double', inputJson: '1e21' },
    { name: 'negative-unsafe-integer', inputJson: '-9007199254740993' },
  ],
  rejectedJs: [
    'undefined',
    'NaN',
    'Infinity',
    '-Infinity',
    'bigint',
    'symbol',
    'function',
    'Date',
    'Map',
    'Set',
    'Uint8Array',
    'class-instance',
    'cycle',
    'lone-surrogate',
    'undefined-in-array',
    'undefined-property',
  ],
};

fs.mkdirSync('packages/core/test/canonical', { recursive: true });
fs.writeFileSync('packages/core/test/canonical/vectors.json', JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${vectors.length} vectors`);
