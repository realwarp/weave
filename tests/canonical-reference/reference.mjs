// Independent reference canonicalizer (RFC 8785, JSON Canonicalization Scheme) in plain JavaScript.
// It shares NO code with packages/core and exists only to cross-check the test vectors (task T0.4).
// Object member names are sorted by UTF-16 code units (RFC 8785 section 3.2.3). Numbers use the
// ECMAScript number-to-string form (RFC 8785 section 3.2.2.3). `-0` is written as `0`.

function encodeString(s) {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c === 0x22) out += '\\"';
    else if (c === 0x5c) out += '\\\\';
    else if (c === 0x08) out += '\\b';
    else if (c === 0x09) out += '\\t';
    else if (c === 0x0a) out += '\\n';
    else if (c === 0x0c) out += '\\f';
    else if (c === 0x0d) out += '\\r';
    else if (c < 0x20) out += '\\u' + c.toString(16).padStart(4, '0');
    else out += s[i];
  }
  return out + '"';
}

function compareUtf16(a, b) {
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) {
    const d = a.charCodeAt(i) - b.charCodeAt(i);
    if (d !== 0) return d;
  }
  return a.length - b.length;
}

export function canonicalize(value) {
  if (value === null) return 'null';
  if (value === true) return 'true';
  if (value === false) return 'false';
  if (typeof value === 'string') return encodeString(value);
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('non-finite number');
    return Object.is(value, -0) ? '0' : String(value);
  }
  if (Array.isArray(value)) return '[' + value.map(canonicalize).join(',') + ']';
  if (typeof value === 'object') {
    const keys = Object.keys(value).sort(compareUtf16);
    return '{' + keys.map((k) => encodeString(k) + ':' + canonicalize(value[k])).join(',') + '}';
  }
  throw new Error('unsupported type: ' + typeof value);
}
